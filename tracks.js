  // серпантин: legs отрезков по x между x0 и x1, шаг по y = S, шпильки радиусом ~S/2
  function serp(x0, x1, y0, S, legs) {
    const pts = [];
    for (let k = 0; k < legs; k++) {
      const y = y0 + k * S, fwd = k % 2 === 0;
      const a = fwd ? x0 : x1, b = fwd ? x1 : x0, dir = Math.sign(b - a);
      pts.push([a + dir * 40, y], [(a + b) / 2, y], [b - dir * 40, y]);
      if (k < legs - 1) { const R = Math.abs(S) / 2; pts.push([b + dir * R * 0.75, y + S * 0.16], [b + dir * R * 1.02, y + S / 2], [b + dir * R * 0.75, y + S * 0.84]); }
    }
    return pts;
  }
